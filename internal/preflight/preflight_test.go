func TestLocalPorts(t *testing.T) {
	root := t.TempDir()
	tests := []struct {
		name, content, state string
		want                 []uint16
	}{
		{"udp", udpFixture, "", []uint16{51820, 53, 5353}},
		{"udp6", udp6Fixture, "", []uint16{51821}},
		{"tcp all states", tcpFixture, "", []uint16{22, 8080, 22}},
		{"tcp listen only", tcpFixture, "0A", []uint16{22, 8080}},
		{"tcp established only", tcpFixture, "01", []uint16{22}},
		{"no match", tcpFixture, "0B", nil},
		{"header only", udpHeader, "", nil},
		{"empty", "", "", nil},
		{"data in first line is skipped as the header", strings.TrimPrefix(udpFixture, udpHeader), "", []uint16{53, 5353}},
		{"malformed lines", udpHeader +
			"garbage\n" +
			"  1: 00000000 00000000:0000 07\n" + // no port separator
			"  2: 00000000:ZZZZ 00000000:0000 07\n" + // bad hex
			"  3: 00000000:10000 00000000:0000 07\n" + // > 16 bits
			"  4: 00000000:0050\n" + // too few fields
			"  5: 00000000:0050 00000000:0000 07 x\n", "", []uint16{80}},
	}
	for _, tt := range tests {
		p := writeAt(t, root, strings.ReplaceAll(tt.name, " ", "_"), tt.content)
		if got := LocalPorts(p, tt.state); !slices.Equal(got, tt.want) {
			t.Errorf("%s: LocalPorts = %v, want %v", tt.name, got, tt.want)
		}
	}
	if got := LocalPorts(filepath.Join(root, "missing"), ""); got != nil {
		t.Errorf("missing file: %v", got)
	}
}

func TestUDPPortInUseAndPickListenPort(t *testing.T) {
	root := t.TempDir()
	s := &System{Root: root}

	// No /proc tables at all: everything is free.
	if s.UDPPortInUse(51820) {
		t.Error("port in use without /proc tables")
	}
	if p := s.PickListenPort(func() uint32 { t.Fatal("random source used"); return 0 }); p != model.DefaultListenPort {
		t.Errorf("PickListenPort = %d, want default", p)
	}

	writeAt(t, root, "proc/net/udp", udpFixture)
	writeAt(t, root, "proc/net/udp6", udp6Fixture)
	for port, want := range map[uint16]bool{51820: true, 51821: true, 53: true, 5353: true, 51822: false, 22: false} {
		if got := s.UDPPortInUse(port); got != want {
			t.Errorf("UDPPortInUse(%d) = %v, want %v", port, got, want)
		}
	}

	// 51820 is taken: a random port in 49152-65535 is chosen, skipping
	// ports that are in use (51821 = 49152 + 2669).
	seq := []uint32{2669, 2669 + 16384, 7}
	i := 0
	next := func() uint32 { v := seq[i%len(seq)]; i++; return v }
	if p := s.PickListenPort(next); p != 49159 {
		t.Errorf("PickListenPort = %d, want 49159", p)
	}
	if i != 3 {
		t.Errorf("random source called %d times, want 3", i)
	}

	// The result always lies in the dynamic range.
	for _, r := range []uint32{0, 1, 16383, 16384, 1<<32 - 1} {
		p := s.PickListenPort(func() uint32 { return r })
		if p < 49152 {
			t.Errorf("PickListenPort(rand=%d) = %d, outside 49152-65535", r, p)
		}
	}

	// Every attempt hits a used port: give up with 0.
	if p := s.PickListenPort(func() uint32 { return 2669 }); p != 0 {
		t.Errorf("PickListenPort with all candidates in use = %d, want 0", p)
	}
}

